// ════════════════════════════════════════════════════════════════
// § canDodge
// ════════════════════════════════════════════════════════════════

describe("canDodge", () => {
  it("returns true when ready and has charges", () => {
    const s = createDodgeState();
    expect(canDodge(s)).toBe(true);
  });

  it("returns false when on cooldown", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(canDodge(s)).toBe(false); // cooldown just started
  });

  it("returns false when no charges remain", () => {
    let s = createDodgeState({ maxCharges: 1 });
    s = startDodge(s, 0);
    // After one dodge with maxCharges=1, charges=0
    // Even after cooldown expires, still no charges
    s = tick(s, 10); // clear cooldown
    expect(s.cooldownTimer).toBe(0);
    // charge should have regenerated by now (10s >> 3s regen)
    // So this will be true again
    expect(canDodge(s)).toBe(true);
  });

  it("returns false when charges are zero and cooldown active", () => {
    let s = createDodgeState({ maxCharges: 1 });
    s = startDodge(s, 0);
    expect(s.charges).toBe(0);
    expect(s.cooldownTimer).toBeGreaterThan(0);
    expect(canDodge(s)).toBe(false);
  });
});

// ════════════════════════════════════════════════════════════════
// § startDodge
// ════════════════════════════════════════════════════════════════

describe("startDodge", () => {
  it("sets isDashing to true", () => {
    const s = startDodge(createDodgeState(), Math.PI / 4);
    expect(s.isDashing).toBe(true);
  });

  it("stores the dash direction", () => {
    const dir = Math.PI / 3;
    const s = startDodge(createDodgeState(), dir);
    expect(s.dashDirection).toBe(dir);
  });

  it("resets dashProgress to 0", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(s.dashProgress).toBe(0);
  });

  it("consumes one charge", () => {
    const base = createDodgeState();
    const s = startDodge(base, 0);
    expect(s.charges).toBe(base.charges - 1);
  });

  it("starts cooldown timer", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(s.cooldownTimer).toBe(s.cooldownDuration);
  });

  it("starts iFrame timer", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(s.iFrameTimer).toBe(s.iFrameDuration);
  });

  it("increments totalDodges", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(s.totalDodges).toBe(1);
  });

  it("returns same state if cannot dodge", () => {
    let s = createDodgeState({ maxCharges: 1 });
    s = startDodge(s, 0); // use the one charge
    const before = s;
    const after = startDodge(s, Math.PI); // should fail
    expect(after).toBe(before); // reference equality — unchanged
  });

  it("does not mutate original state", () => {
    const original = createDodgeState();
    startDodge(original, 0);
    expect(original.charges).toBe(2);
    expect(original.isDashing).toBe(false);
  });
});

// ════════════════════════════════════════════════════════════════
// § tick
// ════════════════════════════════════════════════════════════════

describe("tick", () => {
  it("decrements cooldown timer", () => {
    let s = startDodge(createDodgeState(), 0);
    s = tick(s, 0.5);
    expect(s.cooldownTimer).toBe(1.0);
  });

  it("cooldown does not go below 0", () => {
    let s = startDodge(createDodgeState(), 0);
    s = tick(s, 100);
    expect(s.cooldownTimer).toBe(0);
  });

  it("decrements iFrame timer", () => {
    let s = startDodge(createDodgeState(), 0);
    s = tick(s, 0.1);
    expect(s.iFrameTimer).toBeCloseTo(0.1);
  });

  it("iFrame timer does not go below 0", () => {
    let s = startDodge(createDodgeState(), 0);
    s = tick(s, 10);
    expect(s.iFrameTimer).toBe(0);
  });

  it("advances dash progress", () => {
    let s = startDodge(createDodgeState(), 0);
    s = tick(s, 0.05); // 600 * 0.05 = 30px
    expect(s.dashProgress).toBeCloseTo(30);
    expect(s.isDashing).toBe(true);
  });

  it("ends dash when progress reaches distance", () => {
    let s = startDodge(createDodgeState(), 0);
    // dashDistance=100, dashSpeed=600, time = 100/600 ≈ 0.167s
    s = tick(s, 0.2);
    expect(s.isDashing).toBe(false);
    expect(s.dashProgress).toBe(100);
  });

  it("returns same state for dt <= 0", () => {
    const s = createDodgeState();
    expect(tick(s, 0)).toBe(s);
    expect(tick(s, -1)).toBe(s);
  });

  it("regenerates charges over time", () => {
    let s = createDodgeState({ maxCharges: 2, chargeRegenDuration: 3.0 });
    s = startDodge(s, 0); // charges: 2→1
    // Wait for cooldown to clear and charge to regen
    s = tick(s, 5.0); // 5s > 3s regen
    expect(s.charges).toBe(2);
  });

  it("does not exceed maxCharges during regen", () => {
    const s = createDodgeState();
    const after = tick(s, 100);
    expect(after.charges).toBe(s.maxCharges);
  });

  it("regenerates charges one at a time", () => {
    // Use a long regen so we can control timing precisely
    let s = createDodgeState({ maxCharges: 2, chargeRegenDuration: 5.0 });
    s = startDodge(s, 0); // 2→1 charge
    // Tick just enough for cooldown to clear but NOT enough for a full regen cycle
    s = tick(s, 1.6); // cooldown cleared (1.5s), regen started but not done (5s needed)
    expect(s.charges).toBe(1); // still 1 — regen hasn't completed
    // Dodge again
    s = startDodge(s, 0); // 1→0
    // Now at 0 charges. Tick 5.1s — enough for exactly 1 regen
    s = tick(s, 5.1);
    expect(s.charges).toBe(1); // regenerated 1, not 2
  });
});


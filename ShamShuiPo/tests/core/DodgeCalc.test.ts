// ════════════════════════════════════════════════════════════════
// § Dash physics integration
// ════════════════════════════════════════════════════════════════

describe("dash physics integration", () => {
  it("dash duration equals distance / speed", () => {
    const s = createDodgeState({ dashDistance: 120, dashSpeed: 600 });
    const expectedDuration = 120 / 600; // 0.2s
    let state = startDodge(s, 0);
    // Just before completion
    state = tick(state, expectedDuration - 0.001);
    expect(state.isDashing).toBe(true);
    // Just after completion
    state = tick(state, 0.01);
    expect(state.isDashing).toBe(false);
  });

  it("player cannot change direction mid-dash", () => {
    let s = startDodge(createDodgeState(), Math.PI / 4);
    s = tick(s, 0.05);
    // Attempting another dodge while dashing should fail (on cooldown)
    const after = startDodge(s, Math.PI);
    expect(after.dashDirection).toBe(Math.PI / 4); // unchanged
  });

  it("iFrames start on dodge initiation and last iFrameDuration", () => {
    const s = startDodge(createDodgeState(), 0);
    expect(s.iFrameTimer).toBe(0.2);
    const after = tick(s, 0.2);
    expect(after.iFrameTimer).toBe(0);
  });

  it("full dodge cycle: dodge → dash ends → cooldown expires → dodge again", () => {
    let s = createDodgeState();
    // First dodge
    s = startDodge(s, 0);
    expect(s.isDashing).toBe(true);
    expect(s.charges).toBe(1);

    // Wait for dash to end + cooldown to expire
    s = tick(s, 2.0);
    expect(s.isDashing).toBe(false);
    expect(s.cooldownTimer).toBe(0);

    // Second dodge should work (still has 1 charge)
    expect(canDodge(s)).toBe(true);
    s = startDodge(s, Math.PI);
    expect(s.isDashing).toBe(true);
    expect(s.totalDodges).toBe(2);
  });
});
